#!/usr/bin/env node
// Generates supabase/seed.sql from seed/*.csv (validates first; refuses to write on validation errors).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { parseCsv, validateSeed } from './lib/validate.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const foods = parseCsv(readFileSync(resolve(root, 'seed/foods_fa.csv'), 'utf8'));
const units = parseCsv(readFileSync(resolve(root, 'seed/portion_units.csv'), 'utf8'));
const outPath = resolve(root, 'supabase/seed.sql');

const result = validateSeed(foods, units);
if (!result.ok) {
  for (const e of result.errors) console.error(`error: ${e}`);
  console.error('generate-seed-sql: validation failed, seed.sql not written');
  process.exit(1);
}

const lit = (v) => (v === undefined || v === null || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const numLit = (v, dflt) => (v === undefined || v === '' ? (dflt === undefined ? 'NULL' : String(dflt)) : String(Number(v)));
const tagsLit = (v) => {
  const tags = (v || '').split('|').map((t) => t.trim()).filter(Boolean);
  return `ARRAY[${tags.map(lit).join(',')}]::text[]`;
};

const lines = [];
lines.push('-- Generated by packages/db/scripts/generate-seed-sql.mjs — do not edit by hand.');
lines.push(`-- Source: seed/foods_fa.csv (${foods.records.length} rows), seed/portion_units.csv (${units.records.length} rows)`);
lines.push('begin;');
lines.push('');
lines.push('insert into public.foods (id, name_fa, name_en, source, kcal_100g, protein_100g, carbs_100g, fat_100g, cooked_factor, state, confidence, tags, source_ref, notes) values');
lines.push(
  foods.records
    .map((f) => `  (${[
      lit(f.id), lit(f.name_fa), lit(f.name_en), lit(f.source),
      numLit(f.kcal_100g), numLit(f.protein_100g), numLit(f.carbs_100g), numLit(f.fat_100g),
      numLit(f.cooked_factor, 1), lit(f.state), lit(f.confidence), tagsLit(f.tags), lit(f.source_ref), lit(f.notes),
    ].join(', ')})`)
    .join(',\n'),
);
lines.push('on conflict (id) do update set');
lines.push('  name_fa = excluded.name_fa, name_en = excluded.name_en, source = excluded.source,');
lines.push('  kcal_100g = excluded.kcal_100g, protein_100g = excluded.protein_100g, carbs_100g = excluded.carbs_100g, fat_100g = excluded.fat_100g,');
lines.push('  cooked_factor = excluded.cooked_factor, state = excluded.state, confidence = excluded.confidence,');
lines.push('  tags = excluded.tags, source_ref = excluded.source_ref, notes = excluded.notes;');
lines.push('');
lines.push('insert into public.portion_units (food_id, unit_fa, unit_en, grams_default, grams_min, grams_max, notes) values');
lines.push(
  units.records
    .map((u) => `  (${[
      lit(u.food_id), lit(u.unit_fa), lit(u.unit_en),
      numLit(u.grams_default), numLit(u.grams_min), numLit(u.grams_max), lit(u.notes),
    ].join(', ')})`)
    .join(',\n'),
);
lines.push('on conflict (food_id, unit_fa) do update set');
lines.push('  unit_en = excluded.unit_en, grams_default = excluded.grams_default, grams_min = excluded.grams_min,');
lines.push('  grams_max = excluded.grams_max, notes = excluded.notes;');
lines.push('');
lines.push('commit;');
lines.push('');

writeFileSync(outPath, lines.join('\n'), 'utf8');
console.log(`generate-seed-sql: wrote ${outPath} (${foods.records.length} foods, ${units.records.length} portion units)`);
